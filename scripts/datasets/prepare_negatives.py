"""Prepare negative (non-defect, mostly non-aircraft) images for the domain gate and for background training (Phase 13).

    python scripts/datasets/prepare_negatives.py --imagenet-samples /path/to/imagenet-sample-images

VT-NEG-001  1,000 ImageNet sample images (one per ImageNet class; github.com/EliSchwartz/imagenet-sample-images).
            ImageNet terms: non-commercial research and education. Replace with licensed imagery before commercial
            deployment (docs/MODEL_CARD.md). Three classes show aircraft (airliner, warplane, wing): they are marked
            aircraft=yes and used as gate positives, never as negatives. Airship, space shuttle and aircraft carrier are
            marked ambiguous and left out of both.
VT-NEG-002  Synthetic negatives generated here (CC0): text documents, forms, charts, interface mock-ups, flat colours,
            gradients and noise — the kind of non-photo a user may upload by mistake.

Output: datasets/negatives/<id>/images/* (git-ignored) and datasets/negatives/<id>/manifest.csv (committed):
file, sha256, label, aircraft (yes/no/ambiguous), split (train/valid/test, fixed by a hash of the file name), licence.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import random
import shutil
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "datasets" / "negatives"
AIRCRAFT = {"n02690373": "airliner", "n04552348": "warplane", "n04592741": "wing"}
AMBIGUOUS = {"n02692877": "airship", "n04266014": "space_shuttle", "n02687172": "aircraft_carrier"}


def split_of(name: str) -> str:
    h = int(hashlib.sha256(name.encode()).hexdigest()[:8], 16) % 100
    return "train" if h < 70 else "valid" if h < 85 else "test"


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def imagenet(src: Path) -> list[dict]:
    d = OUT / "VT-NEG-001" / "images"
    d.mkdir(parents=True, exist_ok=True)
    rows = []
    for p in sorted(src.glob("n*_*.JPEG")):
        wnid = p.name.split("_", 1)[0]
        dst = d / p.name
        if not dst.exists():
            shutil.copyfile(p, dst)
        rows.append({"file": f"datasets/negatives/VT-NEG-001/images/{p.name}", "sha256": sha(dst), "label": p.stem.split("_", 1)[1],
                     "aircraft": "yes" if wnid in AIRCRAFT else "ambiguous" if wnid in AMBIGUOUS else "no", "split": split_of(p.name),
                     "licence": "ImageNet terms of access (non-commercial research/education)"})
    return rows


WORDS = ("maintenance schedule invoice summary report quarterly revenue component serial inspection record approved signature date total "
         "customer address meeting agenda notes project timeline budget figure table section appendix reference policy").split()


def synth(n_each: int, seed: int = 13) -> list[dict]:
    d = OUT / "VT-NEG-002" / "images"
    d.mkdir(parents=True, exist_ok=True)
    rng = random.Random(seed)
    rows = []

    def save(img: Image.Image, kind: str, k: int):
        name = f"{kind}_{k:03d}.jpg"
        p = d / name
        img.convert("RGB").save(p, "JPEG", quality=90)
        rows.append({"file": f"datasets/negatives/VT-NEG-002/images/{name}", "sha256": sha(p), "label": kind, "aircraft": "no", "split": split_of(name),
                     "licence": "CC0 (generated by scripts/datasets/prepare_negatives.py)"})

    for k in range(n_each):                                           # text documents
        w, h = rng.choice([(850, 1100), (1100, 850), (900, 600)])
        im = Image.new("RGB", (w, h), tuple(rng.randint(235, 255) for _ in range(3)))
        g = ImageDraw.Draw(im)
        y = rng.randint(30, 80)
        while y < h - 40:
            x = rng.randint(30, 70)
            line = " ".join(rng.choice(WORDS) for _ in range(rng.randint(4, 12)))
            g.text((x, y), line.capitalize(), fill=tuple(rng.randint(0, 70) for _ in range(3)))
            y += rng.randint(18, 34)
            if rng.random() < 0.08:
                g.rectangle([x, y, w - x, y + rng.randint(40, 120)], outline=(90, 90, 90))
                y += 130
        save(im, "document", k)
    for k in range(n_each):                                           # charts
        w, h = 900, 600
        im = Image.new("RGB", (w, h), (255, 255, 255))
        g = ImageDraw.Draw(im)
        g.line([60, 540, 860, 540], fill=(0, 0, 0), width=2); g.line([60, 40, 60, 540], fill=(0, 0, 0), width=2)
        n = rng.randint(4, 12)
        for i in range(n):
            bh = rng.randint(40, 480); x0 = 80 + i * (760 // n)
            g.rectangle([x0, 540 - bh, x0 + 760 // n - 12, 540], fill=tuple(rng.randint(30, 220) for _ in range(3)))
        save(im, "chart", k)
    for k in range(n_each):                                           # interface mock-ups
        w, h = rng.choice([(1280, 800), (390, 844), (1024, 768)])
        bg = tuple(rng.randint(10, 40) for _ in range(3)) if rng.random() < 0.5 else tuple(rng.randint(225, 250) for _ in range(3))
        im = Image.new("RGB", (w, h), bg)
        g = ImageDraw.Draw(im)
        for _ in range(rng.randint(6, 16)):
            x0, y0 = rng.randint(0, w - 60), rng.randint(0, h - 40)
            g.rounded_rectangle([x0, y0, min(w, x0 + rng.randint(60, 400)), min(h, y0 + rng.randint(30, 200))], radius=8,
                                fill=tuple(rng.randint(0, 255) for _ in range(3)))
            g.text((x0 + 8, y0 + 8), rng.choice(WORDS).title(), fill=(255, 255, 255))
        save(im, "interface", k)
    for k in range(n_each):                                           # flat colours, gradients, noise
        w, h = rng.choice([(640, 640), (800, 600)])
        mode = k % 3
        if mode == 0:
            im = Image.new("RGB", (w, h), tuple(rng.randint(0, 255) for _ in range(3)))
        elif mode == 1:
            a, b = [tuple(rng.randint(0, 255) for _ in range(3)) for _ in range(2)]
            im = Image.new("RGB", (w, h))
            px = im.load()
            for y in range(h):
                t = y / h
                c = tuple(int(a[i] * (1 - t) + b[i] * t) for i in range(3))
                for x in range(w):
                    px[x, y] = c
        else:
            im = Image.effect_noise((w, h), rng.randint(20, 90)).convert("RGB").filter(ImageFilter.GaussianBlur(rng.uniform(0, 2)))
        save(im, "plain", k)
    return rows


def write(ds: str, rows: list[dict]) -> None:
    p = OUT / ds / "manifest.csv"
    with open(p, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["file", "sha256", "label", "aircraft", "split", "licence"])
        w.writeheader(); w.writerows(rows)
    print(f"{ds}: {len(rows)} images → {p.relative_to(ROOT)}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--imagenet-samples", type=Path, required=True)
    ap.add_argument("--synthetic-per-kind", type=int, default=60)
    a = ap.parse_args()
    write("VT-NEG-001", imagenet(a.imagenet_samples))
    write("VT-NEG-002", synth(a.synthetic_per_kind))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
