def api_error(status: int, code: str, message: str, /, field: str | None = None, **details: Any) -> HTTPException:
    """Build an HTTPException carrying the standard contract. Raise the returned value."""
    body: dict[str, Any] = {"code": code, "message": message, "details": details}
    if field:
        body["field"] = field
    return HTTPException(status, detail=body)
